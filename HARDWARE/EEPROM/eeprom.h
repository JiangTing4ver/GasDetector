/**
 * @file    eeprom.h
 * @brief   24C02 EEPROM 存储层：标定参数持久化与报警日志
 * @details 24C02 容量为 256 字节，且需与触摸屏校准数据共用同一芯片，
 *          因此地址空间必须严格规划。
 *
 *          ┌──────────┬────────────────────────────────────────────┐
 *          │ 地址范围 │ 用途                                       │
 *          ├──────────┼────────────────────────────────────────────┤
 *          │   0 ~ 39 │ 保留（历史地址，不可占用）                 │
 *          │  40 ~ 53 │ 触摸屏校准参数（touch.c 使用）             │
 *          │  54 ~ 159│ 保留（防止 touch.c 变更造成冲突）          │
 *          │ 160 ~ 167│ 本模块配置区                               │
 *          │ 168 ~ 183│ 保留                                       │
 *          │ 184 ~ 439│ 报警日志环形缓冲区（32 条 × 8 字节）       │
 *          │ 440 ~ 254│ 预留扩展                                   │
 *          │      255 │ 芯片存在性标志 0x55（禁止占用）            │
 *          └──────────┴────────────────────────────────────────────┘
 *
 * @note    日志采用环形缓冲写入。EEPROM 擦写寿命约 100 万次，
 *          若固定地址反复写入会提前失效；环形缓冲使 32 个槽位轮流使用，
 *          等效寿命提升 32 倍。
 */

#ifndef __EEPROM_H
#define __EEPROM_H

#include "sys.h"

/* ==========================================================================
 * 配置区地址分配
 * ========================================================================== */

#define EE_MAGIC_ADDR        160     /**< 初始化标志地址 */
#define EE_MAGIC_VALUE       0x47    /**< 标志值 'G'，表示 EEPROM 已初始化 */
#define EE_R0_ADDR           161     /**< R0 标定值地址，占 4 字节 */
#define EE_LOG_HEAD_ADDR     165     /**< 日志环形缓冲写指针 */
#define EE_LOG_COUNT_ADDR    166     /**< 已存日志条数 */

/* ==========================================================================
 * 日志区配置
 * ========================================================================== */

#define EE_LOG_BASE          184     /**< 日志区起始地址 */
#define EE_LOG_SLOT_SIZE     8       /**< 单条记录字节数 */
#define EE_LOG_SLOT_MAX      32      /**< 环形缓冲槽位数量 */

/** 日志事件来源编码 */
#define EE_SRC_CO_WARN       1       /**< CO 浓度预警 */
#define EE_SRC_CO_ALARM      2       /**< CO 浓度报警 */
#define EE_SRC_BATT_LOW      3       /**< 电池低电量 */
#define EE_SRC_SENSOR_FAIL   4       /**< 传感器异常 */
#define EE_SRC_BOOT          5       /**< 设备开机 */

/* ==========================================================================
 * 数据结构
 * ========================================================================== */

/** 单条日志记录，固定 8 字节 */
typedef struct
{
    u32 time_min;   /**< 开机运行时长 (分钟)，设备无 RTC，以此作为时间戳 */
    u16 co_ppm;     /**< 事件发生时的 CO 浓度 (ppm) */
    u8  temp;       /**< 事件发生时的温度 (℃) */
    u8  src;        /**< 事件来源，取值见 EE_SRC_xxx */
} ee_log_t;

/* ==========================================================================
 * 对外接口
 * ========================================================================== */

/**
 * @brief  初始化 EEPROM 存储层
 * @note   检测 24C02 是否应答；首次使用时初始化配置区并清空日志槽位
 */
void EEPROM_Init(void);

/**
 * @brief  查询 24C02 是否正常应答
 * @retval 1 表示芯片存在且通信正常
 */
u8 EEPROM_IsPresent(void);

/**
 * @brief  读取 R0 标定值
 * @param  r0  输出参数，接收标定值 (Ω)；芯片不存在时返回 0
 */
void EEPROM_ReadR0(u32 *r0);

/**
 * @brief  保存 R0 标定值
 * @param  r0  待保存的标定值 (Ω)
 */
void EEPROM_SaveR0(u32 r0);

/**
 * @brief  追加一条日志记录
 * @param  log  待写入的记录
 * @note   缓冲区写满后自动覆盖最旧记录
 */
void EEPROM_LogAdd(ee_log_t *log);

/**
 * @brief  获取已存储的日志条数
 * @retval 日志条数，上限为 EE_LOG_SLOT_MAX
 */
u16 EEPROM_LogCount(void);

/**
 * @brief  读取指定序号的日志记录
 * @param  index  序号，0 表示最近一条记录，数值越大记录越旧
 * @param  log    输出参数，接收读取结果
 * @retval 1 表示读取成功，0 表示序号越界或数据无效
 */
u8 EEPROM_LogGet(u16 index, ee_log_t *log);

/**
 * @brief  清空全部日志记录
 */
void EEPROM_LogClear(void);

#endif
