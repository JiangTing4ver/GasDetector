/**
 * @file    batt.h
 * @brief   电池电压检测与电量估算
 * @details 采用电阻分压方式测量电池电压，避免超过 ADC 参考电压。
 *
 *          分压电路：
 *              电池正极 ──[ R1 100k ]──┬──[ R2 100k ]── GND
 *                                      │
 *                                      └── PA2 (ADC1_IN2)
 *
 *          电池电压 = 分压点电压 × (R1 + R2) / R2
 *
 * @note    锂电池满电 4.2V 直接接入 ADC 会超过 3.3V 参考电压，
 *          分压后为 2.1V，处于量程范围内。
 */

#ifndef __BATT_H
#define __BATT_H

#include "sys.h"

/* ==========================================================================
 * 硬件与阈值配置
 * ========================================================================== */

/** 电池分压检测所用 ADC 通道 */
#define BATT_ADC_CHANNEL    ADC_Channel_2

/** 分压比 (R1 + R2) / R2。等值电阻分压时为 2 */
#define BATT_DIVIDER_NUM    2

#define BATT_MV_FULL        4200    /**< 满电电压 (mV) */
#define BATT_MV_EMPTY       3300    /**< 空电电压 (mV) */
#define BATT_LOW_MV         3500    /**< 低电量告警阈值 (mV) */
#define BATT_CRIT_MV        3400    /**< 电量严重不足阈值 (mV) */

/* ==========================================================================
 * 数据结构
 * ========================================================================== */

/** 电池状态 */
typedef struct
{
    u16 mv;         /**< 电池电压 (mV) */
    u8  percent;    /**< 剩余电量百分比 (0 ~ 100) */
    u8  low;        /**< 低电量标志 */
    u8  critical;   /**< 电量严重不足标志 */
} batt_data_t;

/** 全局电池数据 */
extern batt_data_t g_batt;

/* ==========================================================================
 * 对外接口
 * ========================================================================== */

/**
 * @brief  初始化电池检测模块
 */
void BATT_Init(void);

/**
 * @brief  电池检测周期任务
 * @note   内部实现 1 秒采样限流，可在任意周期内安全调用
 */
void BATT_Task(void);

#endif
