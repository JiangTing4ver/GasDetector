/**
 * @file    gas_app.h
 * @brief   业务逻辑层：传感器数据聚合、报警判定与日志记录
 * @details 本模块负责设备的核心业务逻辑，不涉及任何界面渲染。
 *          界面层通过读取 g_status 获取展示数据，
 *          从而实现逻辑与界面解耦。
 *
 *          报警设计采用三重防误报机制：
 *            1. 迟滞（Hysteresis）—— 触发阈值与解除阈值分离，
 *               避免浓度停留在阈值附近时状态反复跳变；
 *            2. 持续时间确认 —— 浓度需连续超限一定时间才判定为报警，
 *               过滤火柴、烟雾等瞬时干扰；
 *            3. 预热屏蔽 —— 传感器预热期间输出不稳定，不参与判定。
 */

#ifndef __GAS_APP_H
#define __GAS_APP_H

#include "sys.h"

/* ==========================================================================
 * 报警阈值配置
 * ========================================================================== */

#define GAS_CO_WARN_PPM      25.0f      /**< 预警触发阈值 (ppm) */
#define GAS_CO_WARN_RELEASE  18.0f      /**< 预警解除阈值 (ppm)，迟滞设计 */

#define GAS_CO_ALARM_PPM     50.0f      /**< 报警触发阈值 (ppm) */
#define GAS_CO_ALARM_RELEASE 40.0f      /**< 报警解除阈值 (ppm)，迟滞设计 */

/** 超限持续时间确认 (ms)，用于过滤瞬时干扰 */
#define GAS_CONFIRM_MS       3000UL

/* ==========================================================================
 * 设备状态定义
 * ========================================================================== */

/** 设备工作状态 */
typedef enum
{
    ST_WARMUP = 0,      /**< 传感器预热中，不参与报警判定 */
    ST_NORMAL,          /**< 浓度正常 */
    ST_WARN,            /**< 浓度超过预警阈值 */
    ST_ALARM,           /**< 浓度超过报警阈值并已确认 */
    ST_SENSOR_FAULT     /**< 传感器读数异常（如接线故障、量程饱和） */
} gas_state_t;

/* ==========================================================================
 * 全局状态
 * ========================================================================== */

/** 设备综合状态，为逻辑层与界面层之间唯一的数据接口 */
typedef struct
{
    float       co_ppm;         /**< 当前 CO 浓度 (ppm) */
    u8          co_warm;        /**< 预热中标志 */
    u16         warmup_sec;     /**< 已预热时长 (秒) */
    u8          temp;           /**< 环境温度 (℃) */
    u8          humi;           /**< 相对湿度 (%RH) */
    u8          dht_ok;         /**< 温湿度读取状态 */
    u16         batt_mv;        /**< 电池电压 (mV) */
    u8          batt_pct;       /**< 剩余电量百分比 */
    u8          batt_low;       /**< 低电量标志 */
    gas_state_t state;          /**< 当前设备状态 */
    u32         run_min;        /**< 累计运行时长 (分钟)，作为日志时间戳 */
    u16         log_total;      /**< EEPROM 中累计日志条数 */
    u8          r0_calibrated;  /**< R0 标定状态标志 */
} gas_status_t;

/** 全局设备状态 */
extern gas_status_t g_status;

/* ==========================================================================
 * 对外接口
 * ========================================================================== */

/**
 * @brief  初始化业务逻辑层
 * @note   内部依次初始化 EEPROM、MQ-7、DHT11、电池检测模块，
 *         并写入一条开机日志
 */
void GAS_APP_Init(void);

/**
 * @brief  业务逻辑周期任务
 * @note   建议调用周期 100ms
 */
void GAS_APP_Task(void);

/**
 * @brief  触发洁净空气标定
 * @note   标定结果将写入 EEPROM 持久化保存
 */
void GAS_APP_Calibrate(void);

/**
 * @brief  清空全部报警日志
 */
void GAS_APP_ClearLog(void);

/* ==========================================================================
 * 辅助函数
 * ========================================================================== */

/**
 * @brief  获取设备状态的可读名称
 * @param  st  设备状态
 * @retval 状态名称字符串
 */
const char *GAS_APP_StateName(gas_state_t st);

/**
 * @brief  获取日志事件来源的可读名称
 * @param  src  事件来源编码（EE_SRC_xxx）
 * @retval 事件名称字符串
 */
const char *GAS_APP_LogSrcName(u8 src);

#endif
