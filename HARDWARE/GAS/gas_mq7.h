/**
 * @file    gas_mq7.h
 * @brief   MQ-7 一氧化碳传感器驱动
 * @details 负责 MQ-7 的 ADC 采样、数字滤波、浓度换算与基准电阻标定。
 *
 *          接线要求：
 *            - VCC : 5V      （加热丝工作电流约 150mA，禁止接 3.3V）
 *            - GND : GND
 *            - AO  : PA1     （ADC1_IN1）
 *            - DO  : 不接    （模块板载比较器输出，本项目使用软件阈值）
 *
 *          浓度换算链（详见 docs/DEVELOPER_GUIDE.md 第 6.1 节）：
 *            ADC ──①──> 电压 ──②──> Rs ──③──> Rs/R0 ──④──> ppm
 */

#ifndef __GAS_MQ7_H
#define __GAS_MQ7_H

#include "sys.h"

/* ==========================================================================
 * 硬件参数
 * 更换传感器模块时需核对以下取值
 * ========================================================================== */

/** MQ-7 模拟输出所连接的 ADC 通道 */
#define MQ7_ADC_CHANNEL     ADC_Channel_1

/** 单次采样次数，用于抑制 ADC 随机抖动 */
#define MQ7_ADC_SAMPLE_NUM  16

/** 负载电阻 RL (Ω)。常见 MQ 模块取值为 10kΩ，可查看模块丝印确认（103 = 10k） */
#define MQ7_RL_OHM          10000

/** 传感器回路供电电压 (mV)。模块由 5V 供电时保持 5000 */
#define MQ7_VC_MV           5000

/* ==========================================================================
 * 标定参数
 * 更换传感器后必须重新标定，否则读数不具备参考价值
 * ========================================================================== */

/** 洁净空气中 Rs/R0 的典型比值（取值来源：MQ-7 数据手册，范围 3.6 ~ 4.4） */
#define MQ7_RATIO_CLEAN_AIR 3.8f

/** 浓度曲线系数，ppm = A × (Rs/R0)^B（依据手册双对数曲线拟合） */
#define MQ7_CURVE_A         27.5f
#define MQ7_CURVE_B         (-1.5f)

/** 浓度输出限幅，防止异常读数导致数值溢出 */
#define MQ7_PPM_MIN         0.0f
#define MQ7_PPM_MAX         2000.0f

/**
 * 预热时间 (ms)
 * MQ-7 完全稳定需要 24~48 小时老化，但预热 3~5 分钟即可获得有效读数。
 * 预热期间不参与报警判定，避免开机时输出不稳定造成误报。
 */
#define MQ7_WARMUP_MS       180000UL

/** 一阶低通滤波系数 (0 < α ≤ 1)。α 越小输出越平滑，但响应速度越慢 */
#define MQ7_FILTER_ALPHA    0.25f

/* ==========================================================================
 * 数据结构
 * ========================================================================== */

/** MQ-7 传感器状态与测量结果 */
typedef struct
{
    u16   adc_raw;      /**< 滤波后的 ADC 原始值 (0 ~ 4095) */
    u16   v_out_mv;     /**< 传感器输出电压 (mV) */
    u32   rs_ohm;       /**< 传感器等效电阻 Rs (Ω)，随气体浓度升高而下降 */
    u32   r0_ohm;       /**< 洁净空气基准电阻 R0 (Ω)，由标定流程确定 */
    float ratio;        /**< Rs / R0 比值，数值越大表示空气越洁净 */
    float ppm;          /**< 换算所得 CO 浓度 (ppm) */
    u16   warmup_sec;   /**< 已完成的预热时长 (秒) */
    u8    warmup_done;  /**< 预热完成标志，1 表示读数可信 */
} mq7_data_t;

/** 全局传感器数据，供业务逻辑层读取 */
extern mq7_data_t g_mq7;

/* ==========================================================================
 * 对外接口
 * ========================================================================== */

/**
 * @brief  初始化 MQ-7 驱动
 * @note   内部完成 ADC1 初始化，并从 EEPROM 载入已保存的 R0；
 *         若 EEPROM 中无有效标定值，则使用负载电阻值作为临时占位
 */
void MQ7_Init(void);

/**
 * @brief  MQ-7 周期任务：采样、滤波与浓度换算
 * @param  ms_elapsed  距上次调用的时间间隔 (ms)，用于累计预热时长
 * @retval 1 表示本次已更新测量数据
 * @note   建议调用周期 100ms
 */
u8 MQ7_Task(u16 ms_elapsed);

/**
 * @brief  在洁净空气中执行 R0 标定并写入 EEPROM
 * @note   调用前需确保传感器预热完成，且环境不含酒精、香烟、燃气等干扰源。
 *         误标定会导致后续读数整体偏低，需在洁净空气中重新标定以覆盖
 */
void MQ7_CalibrateCleanAir(void);

/**
 * @brief  立即读取一次 ADC 原始值（不经过滤波）
 * @retval 12 位 ADC 结果
 * @note   仅用于调试，业务逻辑请使用 g_mq7.adc_raw
 */
u16 MQ7_GetRawAdc(void);

#endif
